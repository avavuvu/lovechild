$high: s("supersaw*<2!3 8>")
  // .dec(0.4)
  .legato(3)
  .rel(1)
  .n("<0 0 <3!3 9> <3 8>>/2")
  .scale("<C:major!7 A:minor>")
  .o(2)

$bass: s("saw*2")
  .n("<0 0 3 3>/2")
  .scale("<C1:minor>")
  .when("<0 0 0 1>*2", x => x.trans(12))
  .dist(4)
  .dec(0.5)
  .ply(2)
  .postgain(0.4)
  .lpf(500)

$kick: s("bd bd bd [<- bd> bd]")
  .bank("tr808")
  .dist(3)
  .duck(2)
  .every(4, x=>x.ply(2))
  .duckatt(0.05)

$sd: s("<- cp>*4")
  .dec(0.01)
  .sometimes(x => x.ply(2))
  .bank("tr808")


_$osc: osc($bass.hits(0.2).pow(9).range(2, 4))
  .scale($sd.hits(0.2).range(1,0.4))

$: $osc.sub(previous().moveX($osc))
  .thresh(0.07)
  .colorama("<0.9 0.2 0.3 0.1>*2").r()
  .rotate($high.hits(0.2).range(0.2,0.4))
  .rotate(previous().range(0,0.4))
